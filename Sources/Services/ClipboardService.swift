import AppKit
import Foundation

/// 剪贴板历史：轮询系统剪贴板，记录文本 / 图片，持久化到应用数据目录。
final class ClipboardService: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published var query: String = ""

    var maxItems: () -> Int = { 200 }
    var captureImages: () -> Bool = { true }
    var isEnabled: () -> Bool = { true }

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var suppressedCount: Int = -1
    private let pasteboard = NSPasteboard.general

    private static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ]

    // MARK: 生命周期

    func start() {
        load()
        lastChangeCount = pasteboard.changeCount
        let t = Timer(timeInterval: 0.45, repeats: true) { [weak self] _ in self?.tick() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    // MARK: 轮询

    private func tick() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard count != suppressedCount else { return }
        guard isEnabled() else { return }
        capture()
    }

    private func capture() {
        guard let types = pasteboard.types else { return }
        let typeNames = Set(types.map(\.rawValue))
        if !typeNames.isDisjoint(with: Self.concealedTypes) { return }

        // 文件
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let text = urls.map(\.path).joined(separator: "\n")
            insert(text: text, source: "文件")
            return
        }

        // 图片
        if captureImages(),
           typeNames.contains(NSPasteboard.PasteboardType.png.rawValue) || typeNames.contains(NSPasteboard.PasteboardType.tiff.rawValue),
           let image = NSImage(pasteboard: pasteboard) {
            insert(image: image)
            return
        }

        // 文本
        if let text = pasteboard.string(forType: .string), !text.trimmed.isEmpty {
            insert(text: text, source: nil)
        }
    }

    // MARK: 写入记录

    private func insert(text: String, source: String?) {
        if let idx = items.firstIndex(where: { $0.kind == .text && $0.text == text }) {
            var item = items.remove(at: idx)
            item.date = Date()
            items.insert(item, at: 0)
            save()
            return
        }
        var item = ClipItem(kind: .text, text: text, source: source)
        item.date = Date()
        items.insert(item, at: 0)
        trim()
        save()
    }

    private func insert(image: NSImage) {
        guard let tiff = image.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:]) else { return }

        // 与最新图片做数据比对，避免重复
        if let firstImage = items.first(where: { $0.kind == .image }),
           let name = firstImage.imageFile,
           let existing = try? Data(contentsOf: AppPaths.imagesDir.appendingPathComponent(name)),
           existing == png {
            return
        }

        let name = UUID().uuidString + ".png"
        try? png.write(to: AppPaths.imagesDir.appendingPathComponent(name))
        var item = ClipItem(kind: .image, text: nil, imageFile: name)
        item.date = Date()
        item.source = "\(Int(image.size.width))×\(Int(image.size.height))"
        items.insert(item, at: 0)
        trim()
        save()
    }

    private func trim() {
        let limit = max(20, maxItems())
        guard items.count > limit else { return }
        var kept: [ClipItem] = []
        var normalCount = 0
        for item in items {
            if item.pinned {
                kept.append(item)
                continue
            }
            normalCount += 1
            if normalCount <= limit {
                kept.append(item)
            } else if let f = item.imageFile {
                try? FileManager.default.removeItem(at: AppPaths.imagesDir.appendingPathComponent(f))
            }
        }
        items = kept
    }

    // MARK: 操作

    func image(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        return NSImage(contentsOf: AppPaths.imagesDir.appendingPathComponent(name))
    }

    func copyToPasteboard(_ item: ClipItem) {
        pasteboard.clearContents()
        if item.kind == .image, let name = item.imageFile,
           let data = try? Data(contentsOf: AppPaths.imagesDir.appendingPathComponent(name)) {
            pasteboard.setData(data, forType: .png)
        } else if let text = item.text {
            pasteboard.setString(text, forType: .string)
        }
        suppressedCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount
        // 复制过的置顶
        if let idx = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: idx)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[idx].pinned.toggle()
        save()
    }

    func delete(_ item: ClipItem) {
        if let name = item.imageFile {
            try? FileManager.default.removeItem(at: AppPaths.imagesDir.appendingPathComponent(name))
        }
        items.removeAll { $0.id == item.id }
        save()
    }

    func clearAll() {
        for item in items where item.kind == .image {
            if let name = item.imageFile {
                try? FileManager.default.removeItem(at: AppPaths.imagesDir.appendingPathComponent(name))
            }
        }
        items.removeAll()
        save()
    }

    var filtered: [ClipItem] {
        let q = query.trimmed.lowercased()
        let base = items
        guard !q.isEmpty else { return base }
        return base.filter { $0.previewText.lowercased().contains(q) }
    }

    var pinnedCount: Int { items.filter(\.pinned).count }

    /// 仅供离屏渲染预览使用
    func seedPreview(_ items: [ClipItem]) {
        self.items = items
    }

    // MARK: 持久化

    private func save() {
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .secondsSince1970
        if let data = try? encoder.encode(items) {
            try? data.write(to: AppPaths.clipsFile)
        }
    }

    private func load() {
        guard let data = try? Data(contentsOf: AppPaths.clipsFile) else { return }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .secondsSince1970
        if let decoded = try? decoder.decode([ClipItem].self, from: data) {
            items = decoded
        }
    }
}
